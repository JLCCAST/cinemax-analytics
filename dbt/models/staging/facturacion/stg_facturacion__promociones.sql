select
    id_promotion as id_promocion,
    id_promotion_type as id_tipo_promocion,
    name_promotion as nombre,
    description as descripcion,
    promotion_code as codigo_cupon,
    discount_percentage as porcentaje_descuento,
    discount_fixed_amount as monto_descuento_fijo,
    max_discount_amount as tope_descuento,
    minimum_purchase_amount as compra_minima,
    minimum_ticket_quantity as entradas_minimas,
    start_date as vigente_desde,
    end_date as vigente_hasta,
    day_of_week as dias_semana_iso,
    start_time_from as funcion_desde,
    start_time_to as funcion_antes_de,
    coalesce(exclude_premiere_movies, false) as excluye_estrenos,
    required_snack_category_id as id_categoria_requerida,
    customer_condition as condicion_cliente,
    max_uses_per_user as usos_por_cliente_al_anio,
    applies_to as alcance,
    priority as prioridad,
    status as estado
from {{ source('facturacion', 'promotion') }}
